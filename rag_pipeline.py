"""
rag_pipeline.py — Steps 1, 2, 3A, 4 of the RAG pipeline (Diagram 2).

This module only builds the augmented prompt (R + A). It never calls an
LLM to generate a reply.

Step 5 — the Generator (LLM 2) — is NOT in this file. It's the existing
call_gemini_fn inside chat_module.py's start_chat()/send_message(),
which this project reuses rather than reimplementing. The wiring:

    rag_pipeline.build_augmented_prompt()   -> returns augmented_prompt
    orchestrator.build_rag_context()        -> stores it as
                                                session["system_prompt"]
    chat_module.send_message()              -> reads session["system_prompt"]
                                                and passes it + the user
                                                message into call_gemini_fn
                                                <- this call is Generation

So "G" lives in orchestrator.py (the handoff) + chat_module.py (the
actual Gemini call), not here. Known gap: turn 1's opening message is
generated by chat_module.start_chat() calling Gemini internally BEFORE
orchestrator.build_rag_context() runs, so only turn 2 onward is grounded
in this module's output — see orchestrator.py's start_chat_session()
docstring for the same caveat.

Retrieval (Step 3A) goes through db_layer.query_similar_chunks(), which
returns [] until real embedded knowledge exists — that's an honest empty
result, not a bug, and everything here is expected to behave correctly
with zero chunks.
"""

from __future__ import annotations

import httpx

import db_layer
import gemini_client
from config import GEMINI_EMBEDDING_DIM, GEMINI_EMBEDDING_MODEL

TOP_K_CHUNKS = 5
MAX_PROMPT_TOKENS = 4096


# ══════════════════════════════════════════════════════════════
# STEP 1 — Query Builder
# ══════════════════════════════════════════════════════════════

def build_query(
    combined_scores: dict | None,
    user_query: str | None = None,
    recent_turns: list[str] | None = None,
) -> str:
    """
    Top-3 organ+disease pairs from combined_scores['top_organs'] (the
    shape algorithm_comparison.build_combined_algo_summary() returns), turned into
    the query template from the spec. Appends the user's follow-up
    question + recent chat context if this is a chat turn.
    """
    top_organs = (combined_scores or {}).get("top_organs", [])[:3]

    pairs: list[str] = []
    for entry in top_organs:
        organ = entry.get("organ", "")
        diseases = entry.get("top_diseases") or []
        disease = diseases[0]["disease"] if diseases else organ
        pairs.append(
            f"symptoms and health implications of {disease} affecting {organ} "
            f"in Vedic astrology context"
        )

    query_text = " | ".join(pairs)

    if user_query:
        context = " ".join(recent_turns or [])
        query_text = f"{query_text} | follow-up question: {user_query}"
        if context:
            query_text += f" | recent context: {context}"

    return query_text


# ══════════════════════════════════════════════════════════════
# STEP 2 — Query Embedding
# ══════════════════════════════════════════════════════════════

async def embed_query(text: str) -> list[float]:
    """
    Gemini's embedding endpoint — a different model from chat generation.
    Whatever model embeds queries here MUST be the same one used to embed
    kb_chunks at ingest time, or cosine similarity in Step 3A is
    meaningless (different embedding models don't share a vector space).
    """
    # Vertex AI with the ADC login (gemini_client.py) - API keys are blocked.
    # Same model and size as before, so the vectors stay comparable.
    url = gemini_client.embed_url(GEMINI_EMBEDDING_MODEL)
    headers = await gemini_client.auth_headers()
    payload = {
        "instances": [{"content": text}],
        "parameters": {"outputDimensionality": GEMINI_EMBEDDING_DIM},
    }

    async with httpx.AsyncClient(timeout=30) as client:
        response = await client.post(url, json=payload, headers=headers)
        response.raise_for_status()
        data = response.json()

    return data["predictions"][0]["embeddings"]["values"]


# ══════════════════════════════════════════════════════════════
# STEP 3A — Vector retrieval
# ══════════════════════════════════════════════════════════════

def retrieve_chunks(embedding: list[float], top_k: int = TOP_K_CHUNKS) -> list[dict]:
    """Thin wrapper — the real retrieval logic lives in db_layer.py."""
    return db_layer.query_similar_chunks(embedding, top_k=top_k)


# ══════════════════════════════════════════════════════════════
# STEP 4 — Augmenter
# ══════════════════════════════════════════════════════════════

def _estimate_tokens(text: str) -> int:
    """~4 chars/token — a budgeting heuristic, not an exact tokenizer."""
    return max(1, len(text) // 4)


def build_augmented_prompt(
    system_prompt: str,
    priority_ladder: dict,
    combined_scores: dict,
    kb_chunks: list[dict],
    search_results: dict | None = None,
    user_query: str | None = None,
) -> str:
    """
    Assembles the prompt from: system prompt + de-identified chart
    context + retrieved KB chunks (3A) + LLM 1's web search results (3B,
    search_results — None until llm1_search is wired in by a caller) +
    the user's query. Truncation rule from the spec: if the 4096-token
    budget is exceeded, chunks are dropped starting from the end of the
    list (assumed least-relevant, since retrieve_chunks returns results
    ordered most-similar-first) — the user's current query is never
    truncated, and neither is the search-results section, since it's
    already capped to one organ/disease pair's worth of symptoms.
    """
    chart_section = (
        f"[CHART CONTEXT]\n"
        f"priority_ladder: {priority_ladder}\n"
        f"top_organs: {combined_scores.get('top_organs', [])}"
    )
    query_section = f"[USER QUERY]\n{user_query}" if user_query else ""

    search_section = ""
    if search_results and search_results.get("symptoms"):
        search_section = (
            f"[WEB SEARCH RESULTS]\n"
            f"symptoms: {search_results['symptoms']}\n"
            f"sources: {search_results.get('web_sources', [])}"
        )

    fixed_cost = (
        _estimate_tokens(system_prompt)
        + _estimate_tokens(chart_section)
        + _estimate_tokens(query_section)
        + _estimate_tokens(search_section)
    )
    budget = MAX_PROMPT_TOKENS - fixed_cost

    kept_chunks: list[str] = []
    for chunk in kb_chunks:
        chunk_text = chunk.get("text", "")
        cost = _estimate_tokens(chunk_text)
        if cost > budget:
            break
        kept_chunks.append(chunk_text)
        budget -= cost

    parts = [system_prompt, chart_section]
    if kept_chunks:
        parts.append("[RETRIEVED KNOWLEDGE]\n" + "\n---\n".join(kept_chunks))
    if search_section:
        parts.append(search_section)
    if query_section:
        parts.append(query_section)

    return "\n\n".join(parts)


