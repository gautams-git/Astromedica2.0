# 3B. Retrieval (Web)  LLM 1_search.search_symptoms() [llm1_search.py]
#      top organ/disease -> Serper search -> Gemini parse -> search_results
#
# 4. Augmenter         build_augmented_prompt()    [this file]
#      system_prompt + chart context + kb_chunks + search_results
#      + user_query -> augmented_prompt (4096-token budget, oldest
#      chunks dropped first)
#
# 5. Generator (LLM 2) call_gemini_fn              [chat_module.py]
#      orchestrator.build_rag_context() stores augmented_prompt as
#      session["system_prompt"]; chat_module.send_message() reads it
#      and calls Gemini -> the reply the patient sees.
